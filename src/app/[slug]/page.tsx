import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import { Suspense } from 'react';
import { ProfileContent } from '@/components/public/profile-content';
import { isAgentPage } from '@/lib/agent-profiles';
import { resolvePublicProfileSlug } from '@/lib/demo-profiles';
import { metadataForProfile } from '@/lib/public-route-metadata';
import { resolveThemeConfig } from '@/lib/themes';

import { getFullPageData } from './_lib/get-page-data';

// Force into the static-renderable pipeline so the OpenNext incremental
// cache + Next.js Cache-Control headers actually apply.
export const dynamic = 'force-static';
export const revalidate = 60;

type Props = {
  params: Promise<{ slug: string }>;
};

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const requestedSlug = (await params).slug;
  const slug = resolvePublicProfileSlug(requestedSlug);
  const data = await getFullPageData(slug);
  if (!data) return {};

  const { page, modeContent } = data;
  const isAgent = isAgentPage(page);
  // Dynamic OG generated by /api/og?slug=…&... — turns out the
  // OpenNext+CF Workers hang was specific to [slug] dynamic-param
  // routes. A static API path that reads from query string works
  // fine. So generateMetadata bakes every datum the renderer needs
  // into the og:image URL (display name, live newspaper headline
  // or bio, location, theme accent) and the edge cache absorbs
  // repeated shares of the same content.
  const theme = resolveThemeConfig(page.themeConfig);
  const newsHeadline = modeContent.newspaper?.headline;
  const liveHeadline =
    typeof newsHeadline === 'string' && newsHeadline.trim()
      ? newsHeadline.trim()
      : null;
  const ogHeadline =
    liveHeadline ??
    (isAgent ? page.agentPurpose : null) ??
    page.bio ??
    `${page.displayName} on Karte`;
  const ogParams = new URLSearchParams({
    slug,
    name: page.displayName,
    h: ogHeadline.slice(0, 200),
    loc: (isAgent ? page.agentOperator : page.location) ?? '',
    accent: theme.accentColor.replace('#', ''),
    live: liveHeadline ? '1' : '0',
  });
  const ogUrl = `/api/og?${ogParams.toString()}`;

  return metadataForProfile({
    path: `/${slug}`,
    displayName: page.displayName,
    description:
      (isAgent ? page.agentPurpose : null) ??
      page.bio ??
      `${page.displayName} on Karte — links, chat, and more.`,
    image: ogUrl,
  });
}

